function addDaysISO(daysFromNow: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysFromNow);
  return d.toISOString().slice(0, 10);
}

export function createPredefinedRoadmap(): RoadmapTopic[] {
  const levels: CEFRLevel[] = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];
  const allTopics: RoadmapTopic[] = [];
  let globalOrder = 1;

  for (const level of levels) {
    const specs = TOPICS_BY_LEVEL[level];
    specs.forEach((spec, idx) => {
      // Seed realistic starter progress on initial A1 lessons so deadlines & speaking consolidation shine immediately
      let status: RoadmapTopic['status'] = 'not_started';
      let deadline: string | null = null;
      let completedDrills: number[] = [];

      if (level === 'A1' && idx < 4) {
        status = 'mastered';
        completedDrills = [0, 1, 2];
        deadline = addDaysISO(-10 + idx * 2);
      } else if (level === 'A1' && idx === 4) {
        status = 'consolidating';
        completedDrills = [0, 1];
        deadline = addDaysISO(2);
      } else if (level === 'A1' && idx === 5) {
        status = 'in_progress';
        completedDrills = [0];
        deadline = addDaysISO(5);
      } else if (level === 'A1' && idx === 6) {
        status = 'not_started';
        deadline = addDaysISO(9);
      }

      allTopics.push({
        id: `topic-${level.toLowerCase()}-${idx + 1}`,
        level,
        order: globalOrder++,
        title: spec.title,
        description: spec.description,
        grammarFocus: spec.grammarFocus,
        keyVocabulary: spec.keyVocabulary,
        speakingFocusPrompt: spec.speakingFocusPrompt,
        speakingDrills: spec.speakingDrills,
        estimatedMinutes: spec.estimatedMinutes,
        deadline,
        status,
        completedDrills,
        isCustom: false,
      });
    });
  }

  return allTopics;
}
